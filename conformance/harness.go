// Matrix renders the generated support matrix markdown.
func Matrix() string {
	var buf strings.Builder
	buf.WriteString("# Support matrix\n\n")
	buf.WriteString("> Generated by `go test ./conformance -run TestGenerateSupportMatrix -update`. ")
	buf.WriteString("Do not edit by hand.\n\n")
	buf.WriteString("A model is listed as supported only when its driver-in-the-loop conformance case passes.\n\n")
	buf.WriteString("## Supported\n\n")
	buf.WriteString("| Model | Driver | Coverage |\n|---|---|---|\n")
	sorted := Cases()
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Model < sorted[j].Model })
	for _, c := range sorted {
		if c.Run == nil {
			continue
		}
		fmt.Fprintf(&buf, "| `%s` | %s | %s |\n", c.Model, c.Driver, c.Summary)
	}
	buf.WriteString("\n## Unsupported (with rationale)\n\n")
	buf.WriteString("| Driver | Rationale |\n|---|---|\n")
	unsupportedSorted := Unsupported()
	sort.Slice(unsupportedSorted, func(i, j int) bool { return unsupportedSorted[i].Driver < unsupportedSorted[j].Driver })
	for _, u := range unsupportedSorted {
		fmt.Fprintf(&buf, "| %s | %s |\n", u.Driver, u.Rationale)
	}
	buf.WriteString("\n## Generic fallback\n\n")
	buf.WriteString("Any driver whose chip model is not listed above can still attach to the generic ")
	buf.WriteString("`register-map` chip. It exposes raw registers through the bus console and the UI, ")
	buf.WriteString("but is not claimed as behaviourally supported.\n")
	return buf.String()
}
