// Package conformance contains the driver-in-the-loop harness. A chip or
// driver is only listed as supported in docs/support-matrix.md when its case
// passes here.
package conformance

import (
	"context"
	"fmt"
	"sort"
	"strings"

	simulate "github.com/disaster37/gobot-simulate"
)

// Case is one driver-in-the-loop conformance case.
type Case struct {
	Model   string
	Driver  string
	Summary string
	Run     func(env *Env) error
}

// Env is the simulator context handed to a case.
type Env struct {
	Sim     *simulate.Simulator
	Board   string
	Adaptor *simulate.Adaptor
}

// NewEnv creates a simulator with one board and optional topology.
func NewEnv(boardID, topologyYAML string) (*Env, error) {
	sim := simulate.New(
		simulate.WithAddr("127.0.0.1"),
		simulate.WithPort(0),
		simulate.WithUIEnabled(false),
	)
	if topologyYAML != "" {
		if err := sim.LoadTopology(strings.NewReader(topologyYAML)); err != nil {
			return nil, err
		}
	}
	adaptor := sim.Adaptor(boardID)
	return &Env{Sim: sim, Board: boardID, Adaptor: adaptor}, nil
}

// StartServer starts the HTTP surface for cases that drive network adaptors.
